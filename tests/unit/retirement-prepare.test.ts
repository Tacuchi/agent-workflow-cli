import { prepareRetirement } from "../../src/application/retirement/prepare.js";
import type { PrepareDeps } from "../../src/application/retirement/prepare.js";
import {
  renderRetirementPreview,
  retirementPreview,
} from "../../src/application/retirement/preview.js";
